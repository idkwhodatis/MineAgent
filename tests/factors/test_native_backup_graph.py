"""Synthetic cross-closure regression with actual files, NOT DB/runtime proof.

Research/RD dependency closures are inputs assumed separately validated by their
own validators. This fixture tests native joins/hashes and never claims a real
process ran or a source was generated by a model.
"""

import copy
import hashlib
import json
from datetime import timedelta
from uuid import uuid4

import pytest

from backend.app import factor_native_backup as backup
from backend.app.factor_native_io import publish_candidate_bytes
from backend.app.factor_native_services import footprint
from backend.app.services import DomainError
from packages.factors.contracts import digest
from packages.factors.native_publication import NativePublicationIntent
from packages.factors.v2_evidence import EvidenceObject
from packages.factors.v2_storage_contracts import storage_identity
from packages.rdagent_adapter.numeric_profile import candidate_inputs
from packages.research_runtime.budget_contracts import BudgetVector
from packages.research_runtime.numeric_process_journal import (
    NumericInput,
    NumericIntent,
)
from packages.research_runtime.process_declarations_v2 import ProcessDeclarationV2
from packages.research_runtime.process_persistence_codec import encode_row
from tests.rdagent.test_rdagent_numeric_profile import projected


def graph(root):
    config, snapshot, prefix, files, source_bytes, source_hash = projected()
    scope = {
        "owner_id": uuid4(),
        "run_id": uuid4(),
        "attempt_id": uuid4(),
        "generation": 1,
    }
    code_id, source_id, start_id, cutoff_id = uuid4(), uuid4(), uuid4(), uuid4()
    refs, _, _ = candidate_inputs(
        prefix,
        snapshot_input=snapshot,
        source=source_bytes,
        expected_source_sha256=source_hash,
        projected_files=files,
    )
    inputs = NumericInput(
        schema_version="mineagent.numeric-process-input.v2",
        source_object_id=code_id,
        source_sha256=source_hash,
        prefix_sha256=prefix.sha256,
        cutoff=prefix.host_cutoff,
        files=tuple(
            {
                "destination": x.destination,
                "sha256": x.sha256,
                "size_bytes": x.size_bytes,
            }
            for x in refs
        ),
    )
    admission = ProcessDeclarationV2(
        schema_version="mineagent.process-admission.v2",
        id=uuid4(),
        **scope,
        role="factor_cutoff_candidate",
        logical_operation_id=cutoff_id,
        launch_ordinal=1,
        profile=prefix.candidate_profile,
        input_sha256=digest(inputs),
        reservation_id=uuid4(),
        image_id=prefix.candidate_image,
        ipc={"ipc_policy": "none", "ticket_sha256": None},
    )
    process_intent = NumericIntent(
        schema_version="mineagent.numeric-process-intent.v2",
        id=uuid4(),
        admission=admission,
        inputs=inputs,
        issued_at=prefix.host_cutoff,
        not_after=prefix.host_cutoff + timedelta(seconds=10),
    )
    opaque = b"synthetic opaque output; no parser or runtime acceptance"
    output = storage_identity(
        scope["owner_id"],
        EvidenceObject(
            role="native_hdf",
            object_id=uuid4(),
            object_kind="native_hdf",
            media_type="application/x-hdf5",
            sha256=hashlib.sha256(opaque).hexdigest(),
            size_bytes=len(opaque),
        ),
    )
    raw_scope = {k: str(v) if k.endswith("_id") else v for k, v in scope.items()}
    receipts = []
    for kind, payload in (
        ("launch_intent", process_intent.model_dump(mode="json")),
        ("launch_identity", {"synthetic": True}),
        (
            "stop",
            {
                "synthetic": True,
                "deadline_bound_met": True,
                "observed_at": prefix.host_cutoff.isoformat(),
            },
        ),
        (
            "extraction",
            {
                "basename": "result.h5",
                "sha256": output.object.sha256,
                "size_bytes": len(opaque),
            },
        ),
    ):
        receipts.append(
            dict(
                id=str(uuid4()),
                **raw_scope,
                admission_id=str(admission.id),
                kind=kind,
                payload=payload,
                payload_sha256=digest(payload),
            )
        )
    st, ex = receipts[2:]
    journal, reservation = uuid4(), uuid4()
    intent = NativePublicationIntent(
        schema_version="mineagent.candidate-native-intent.v2",
        journal_id=journal,
        reservation_id=reservation,
        admission=admission,
        source_id=source_id,
        generation_start_id=start_id,
        factor_version_id=snapshot.version.factor_version_id,
        source_object_id=code_id,
        source_sha256=source_hash,
        prefix_sha256=prefix.sha256,
        snapshot_input_sha256=snapshot.sha256,
        cutoff=prefix.host_cutoff,
        stop_receipt_id=st["id"],
        stop_receipt_sha256=st["payload_sha256"],
        extraction_receipt_id=ex["id"],
        extraction_receipt_sha256=ex["payload_sha256"],
        output=output,
        journal_key=f"factors/{scope['owner_id']}/native-journals/{journal}.json",
    )
    peak, entries = footprint(intent)
    pub = dict(
        id=str(journal),
        **raw_scope,
        cutoff_id=str(cutoff_id),
        admission_id=str(admission.id),
        reservation_id=str(reservation),
        source_id=str(source_id),
        source_object_id=str(code_id),
        source_sha256=source_hash,
        stop_receipt_id=st["id"],
        extraction_receipt_id=ex["id"],
        stop_kind="stop",
        extraction_kind="extraction",
        intent=intent.model_dump(mode="json"),
        intent_sha256=digest(intent),
        object_id=str(output.object.object_id),
        sha256=output.object.sha256,
        size_bytes=len(opaque),
        storage_key=output.storage_key,
        journal_key=intent.journal_key,
        peak_bytes=peak,
        peak_entries=entries,
        created_at="2020-01-01T00:00:00Z",
    )
    obj = {
        key: pub[key]
        for key in ("owner_id", "sha256", "size_bytes", "storage_key", "created_at")
    }
    obj.update(
        id=pub["object_id"], object_kind="native_hdf", media_type="application/x-hdf5"
    )
    outcome = {
        key: pub[key]
        for key in (
            "owner_id",
            "object_id",
            "sha256",
            "size_bytes",
            "storage_key",
            "created_at",
        )
    }
    physical = {
        "storage_key": pub["storage_key"],
        "sha256": pub["sha256"],
        "size_bytes": pub["size_bytes"],
        "journal_key": pub["journal_key"],
        "journal_sha256": pub["intent_sha256"],
    }
    outcome.update(
        publication_id=pub["id"],
        journal_sha256=pub["intent_sha256"],
        physical_receipt_sha256=digest(physical),
    )
    claim = dict(
        reservation_id=str(reservation),
        **raw_scope,
        consumer_kind="native_hdf",
        consumer_id=str(journal),
    )
    native = {
        "schema_version": backup.SCHEMA,
        "tables": {name: [] for name in backup.FIELDS},
    }
    for name, value in (
        ("factor_native_publications", pub),
        ("factor_native_objects", obj),
        ("factor_native_outcomes", outcome),
        ("engine_object_reservation_consumers", claim),
    ):
        native["tables"][name] = [value]
    amounts = BudgetVector(storage_bytes=peak).model_dump()
    research = {
        "tables": {
            "research_process_admissions": [
                {
                    k: str(v) if hasattr(v, "hex") else v
                    for k, v in encode_row(admission).items()
                }
            ],
            "research_process_receipts": receipts,
            "research_budget_reservations": [
                dict(
                    id=str(reservation),
                    **raw_scope,
                    purpose="object_storage",
                    logical_key="native:" + str(journal),
                    amounts=amounts,
                    state="settled",
                )
            ],
            "research_budget_settlements": [
                {
                    "id": str(uuid4()),
                    "reservation_id": str(reservation),
                    "charge": amounts,
                    "outcome": "conservative_unknown",
                }
            ],
        }
    }
    evaluation_id = str(uuid4())
    rd = {
        "tables": {
            "factor_generation_sources": [
                dict(
                    id=str(source_id),
                    **raw_scope,
                    source_sha256=source_hash,
                    factor_version_id=str(snapshot.version.factor_version_id),
                )
            ],
            "factor_cutoff_executions": [
                dict(
                    id=str(cutoff_id),
                    **raw_scope,
                    evaluation_id=evaluation_id,
                    cutoff_ordinal=0,
                    start_id=str(start_id),
                    candidate_admission_id=str(admission.id),
                    evaluated_source_id=str(source_id),
                    projection_sha256=prefix.sha256,
                    projection=prefix.model_dump(mode="json"),
                )
            ],
            "factor_evaluation_starts": [
                dict(
                    id=evaluation_id,
                    **raw_scope,
                    input_sha256=snapshot.sha256,
                    expected_cutoffs=1,
                    snapshot_input=snapshot.model_dump(mode="json"),
                )
            ],
            "factor_research_specs": [
                {
                    "id": str(uuid4()),
                    "owner_id": raw_scope["owner_id"],
                    "run_id": raw_scope["run_id"],
                    "config": config.model_dump(mode="json"),
                    "config_sha256": config.sha256,
                }
            ],
        }
    }
    (root / "factors").mkdir()
    publish_candidate_bytes(root, intent, opaque)
    inventory = []
    for key in (intent.journal_key, output.storage_key):
        data = (root / key).read_bytes()
        inventory.append(
            {
                "path": key,
                "sha256": hashlib.sha256(data).hexdigest(),
                "size_bytes": len(data),
            }
        )

    def check(key, sha, size):
        data = (root / key).read_bytes()
        assert len(data) == size and hashlib.sha256(data).hexdigest() == sha

    def validate(value):
        backup.validate_closure(
            value,
            check,
            lambda key: json.loads((root / key).read_bytes()),
            100,
            inventory=inventory,
            research_closure=research,
            rd_source_closure=rd,
        )

    return native, validate


def test_synthetic_complete_native_crossclosure_checks_actual_opaque_files(tmp_path):
    native, validate = graph(tmp_path)
    validate(native)


@pytest.mark.parametrize(
    "field",
    [
        "sha256",
        "intent_sha256",
        "source_sha256",
        "storage_key",
        "journal_key",
        "peak_bytes",
        "stop_receipt_id",
        "source_id",
    ],
)
def test_native_crossclosure_rejects_substituted_registered_row(tmp_path, field):
    native, validate = graph(tmp_path)
    bad = copy.deepcopy(native)
    row = bad["tables"]["factor_native_publications"][0]
    row[field] = (
        row[field] + 1
        if type(row[field]) is int
        else str(uuid4())
        if field.endswith("_id")
        else "different"
    )
    with pytest.raises((ValueError, DomainError)):
        validate(bad)
