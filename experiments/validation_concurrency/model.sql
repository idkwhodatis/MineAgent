-- RECONSTRUCTED ISOLATED GLOBAL-GATE REFERENCE. NEVER EXECUTED HERE.
-- Not actual RD predicates, no deduplication, no production lock integration.
CREATE SCHEMA __SCHEMA__;
COMMENT ON SCHEMA __SCHEMA__ IS 'owned isolated validation coordination model';
CREATE TABLE __SCHEMA__.parent (id integer PRIMARY KEY);
CREATE TABLE __SCHEMA__.workflow (
 id integer PRIMARY KEY, owner_id integer NOT NULL, parent_id integer NOT NULL
);
CREATE TABLE __SCHEMA__.receipt (workflow_id integer PRIMARY KEY);
CREATE FUNCTION __SCHEMA__.writer_gate() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF NOT pg_try_advisory_xact_lock(__KEY__::bigint) THEN
  RAISE EXCEPTION USING ERRCODE='55P03', MESSAGE='model_writer_busy';
 END IF;
 RETURN NULL;
END $$;
CREATE FUNCTION __SCHEMA__.validate_graph() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM __SCHEMA__.workflow w
   WHERE NOT EXISTS(SELECT 1 FROM __SCHEMA__.parent p WHERE p.id=w.parent_id))
 OR EXISTS(SELECT 1 FROM __SCHEMA__.workflow w
   WHERE NOT EXISTS(SELECT 1 FROM __SCHEMA__.receipt r WHERE r.workflow_id=w.id))
 OR EXISTS(SELECT 1 FROM __SCHEMA__.receipt r
   WHERE NOT EXISTS(SELECT 1 FROM __SCHEMA__.workflow w WHERE w.id=r.workflow_id))
 THEN RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='model_graph_invalid'; END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER admission BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE
 ON __SCHEMA__.parent FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.writer_gate();
CREATE TRIGGER admission BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE
 ON __SCHEMA__.workflow FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.writer_gate();
CREATE TRIGGER admission BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE
 ON __SCHEMA__.receipt FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.writer_gate();
CREATE FUNCTION __SCHEMA__.reject_truncate() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION USING ERRCODE='0A000', MESSAGE='model_truncate_unsupported'; END $$;
CREATE TRIGGER no_truncate BEFORE TRUNCATE ON __SCHEMA__.parent
 FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.reject_truncate();
CREATE TRIGGER no_truncate BEFORE TRUNCATE ON __SCHEMA__.workflow
 FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.reject_truncate();
CREATE TRIGGER no_truncate BEFORE TRUNCATE ON __SCHEMA__.receipt
 FOR EACH STATEMENT EXECUTE FUNCTION __SCHEMA__.reject_truncate();
CREATE CONSTRAINT TRIGGER graph_valid AFTER INSERT OR UPDATE OR DELETE
 ON __SCHEMA__.parent DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION __SCHEMA__.validate_graph();
CREATE CONSTRAINT TRIGGER graph_valid AFTER INSERT OR UPDATE OR DELETE
 ON __SCHEMA__.workflow DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION __SCHEMA__.validate_graph();
CREATE CONSTRAINT TRIGGER graph_valid AFTER INSERT OR UPDATE OR DELETE
 ON __SCHEMA__.receipt DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION __SCHEMA__.validate_graph();
